#!/usr/bin/env python3
"""Run the SQL files and save their real outputs to results/.

What it does:
  1. Runs sql/02_data_quality.sql and saves every check as a table in
     results/data_quality.md.
  2. Runs sql/03_analysis.sql and saves one CSV per query in results/.
  3. Runs sql/04_warehouse_views.sql (creates the views) and saves their
     contents in results/views.md.

Nothing here is hand-written: every number in results/ came out of the
database in this run. Run it after load_data.py:

    python3 load_data.py
    python3 run_queries.py

Or run everything at once with:  bash build.sh
"""

import csv
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SQL_DIR = ROOT / "sql"
RESULTS = ROOT / "results"
DB_PATH = ROOT / "labour_warehouse.db"


def split_statements(sql_text):
    """Split SQL into single statements, using SQLite's own parser.

    First, drop full-line '--' comments (they carry no SQL). Then feed
    the rest to sqlite3.complete_statement, which knows where a real
    statement ends. Splitting on ';' by hand would break if a text value
    ever contained a ';' inside it — this way it cannot.
    """
    code_lines = [ln for ln in sql_text.splitlines()
                  if not ln.strip().startswith("--")]
    statements = []
    buffer = ""
    for line in code_lines:
        buffer += line + "\n"
        if sqlite3.complete_statement(buffer):
            statements.append(buffer.strip())
            buffer = ""
    if buffer.strip():
        statements.append(buffer.strip())
    return statements


def split_sections(path, marker):
    """Split a SQL file into (number, title, sql) sections.

    A section starts with a line like '-- CHECK 1: Row counts ...' or
    '-- Q1 — Which province ...' and runs until the next such line.
    """
    text = (SQL_DIR / path).read_text(encoding="utf-8")
    pattern = re.compile(rf"^-- {marker}\s*(\d+)\s*(?:\(NOTE\))?\s*[—:\-]\s*(.*)$", re.M)
    matches = list(pattern.finditer(text))
    sections = []
    for i, m in enumerate(matches):
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections.append((int(m.group(1)), m.group(2).strip(),
                         text[start:end]))
    return sections


def slug(text):
    """Turn a question title into a short file-name slug."""
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "_", text).strip("_")
    return text[:48].rstrip("_")


# Short, readable file names for the ten analysis outputs.
Q_SLUGS = {
    1: "province_unemployment_ranking",
    2: "youth_by_province_and_sex",
    3: "youth_vs_total_gap_by_year",
    4: "trend_by_decade",
    5: "gender_gap_by_year",
    6: "yoy_change_ranked",
    7: "education_gradient",
    8: "neet_change_by_province",
    9: "rural_vs_urban",
    10: "years_youth_above_10pct",
    11: "lfpr_trend",
}


def markdown_table(headers, rows):
    """Render query output as a Markdown table."""
    lines = ["| " + " | ".join(headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(
            "" if v is None else str(v) for v in row) + " |")
    return "\n".join(lines)


def main():
    if not DB_PATH.exists():
        raise SystemExit("labour_warehouse.db not found — run load_data.py first.")
    RESULTS.mkdir(exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    cur = con.cursor()

    # 1. Data-quality checks -> results/data_quality.md ----------------------
    dq_lines = ["# Data-quality checks",
                "",
                "Output of `sql/02_data_quality.sql`, run against the freshly "
                "built database. Generated by `run_queries.py` — nothing here "
                "was typed by hand.",
                ""]
    for num, title, sql in split_sections("02_data_quality.sql", "CHECK"):
        stmts = split_statements(sql)
        assert len(stmts) == 1, f"CHECK {num} should be one statement, got {len(stmts)}"
        cur.execute(stmts[0])
        headers = [d[0] for d in cur.description]
        rows = cur.fetchall()
        dq_lines.append(f"## CHECK {num}: {title}")
        dq_lines.append("")
        dq_lines.append(markdown_table(headers, rows))
        dq_lines.append("")
        print(f"  CHECK {num}: {len(rows)} row(s)")
    (RESULTS / "data_quality.md").write_text("\n".join(dq_lines), encoding="utf-8")

    # 2. Analysis queries -> one CSV per query -------------------------------
    for num, title, sql in split_sections("03_analysis.sql", "Q"):
        stmts = split_statements(sql)
        assert len(stmts) == 1, f"Q{num} should be one statement, got {len(stmts)}"
        cur.execute(stmts[0])
        headers = [d[0] for d in cur.description]
        rows = cur.fetchall()
        name = f"q{num:02d}_{Q_SLUGS.get(num, slug(title))}.csv"
        with open(RESULTS / name, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(headers)
            w.writerows(rows)
        print(f"  Q{num}: {len(rows)} row(s) -> results/{name}")

    # 3. Views -> results/views.md -------------------------------------------
    cur.executescript((SQL_DIR / "04_warehouse_views.sql").read_text(encoding="utf-8"))
    view_lines = ["# Warehouse views",
                  "",
                  "Output of the views in `sql/04_warehouse_views.sql`, run "
                  "against the freshly built database.",
                  ""]
    for view in ("v_province_summary", "v_youth_trend", "v_gender_gap"):
        cur.execute(f"SELECT * FROM {view}")
        headers = [d[0] for d in cur.description]
        rows = cur.fetchall()
        view_lines.append(f"## {view} ({len(rows)} rows)")
        view_lines.append("")
        view_lines.append(markdown_table(headers, rows))
        view_lines.append("")
        print(f"  {view}: {len(rows)} row(s)")
    (RESULTS / "views.md").write_text("\n".join(view_lines), encoding="utf-8")

    con.close()
    print("Results written to results/")


if __name__ == "__main__":
    main()
